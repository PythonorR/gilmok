"""Shared FastAPI dependencies that turn raw query params into validated values."""

from typing import Annotated

from fastapi import Header, Query

from app.core.config import get_settings
from app.core.errors import bad_request
from app.core.params import (
    BBox,
    parse_bbox,
    parse_weights,
    validate_category,
    validate_point,
    validate_radius,
)

# Fallback until the active score_config is read from the database (Step 5).
DEFAULT_WEIGHTS = {
    "demand": 0.35,
    "competition": 0.25,
    "accessibility": 0.20,
    "growth": 0.10,
    "cost": 0.10,
}


class PointQuery:
    def __init__(
        self,
        lat: Annotated[float, Query(description="위도 (WGS84)")],
        lng: Annotated[float, Query(description="경도 (WGS84)")],
        radius: Annotated[int, Query(description="분석 반경 (m): 300, 500, 1000")] = 500,
        category: Annotated[str, Query(description="업종 키")] = "cafe",
    ) -> None:
        validate_point(lat, lng)
        self.lat, self.lng = lat, lng
        self.radius = validate_radius(radius)
        self.category = validate_category(category, get_settings().enabled_categories)


def category_param(category: Annotated[str, Query()] = "cafe") -> str:
    return validate_category(category, get_settings().enabled_categories)


def weights_param(
    weights: Annotated[
        str | None, Query(description="예: demand:0.35,competition:0.25,accessibility:0.2")
    ] = None,
) -> dict[str, float]:
    return parse_weights(weights, DEFAULT_WEIGHTS)


def bbox_param(
    bbox: Annotated[str, Query(description="minLng,minLat,maxLng,maxLat")],
) -> BBox:
    return parse_bbox(bbox, get_settings().max_bbox_area_km2)


def owner_key(x_owner_key: Annotated[str, Header(min_length=16, max_length=64)]) -> str:
    """Anonymous session key generated by the browser (no accounts in the MVP)."""
    if not x_owner_key.replace("-", "").isalnum():
        raise bad_request("INVALID_OWNER_KEY", "세션 키 형식이 올바르지 않습니다.")
    return x_owner_key
